"""Render docs/perf.md tables from games' `_work/worker.jsonl` logs."""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

from .dag import LOG_REL


def read_log(game_dir: Path) -> list[dict]:
    path = Path(game_dir) / LOG_REL
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _duration(game_dir: Path) -> float | None:
    try:
        return float(json.loads((Path(game_dir) / "game.json").read_text())["video"]["duration_s"])
    except (OSError, ValueError, KeyError, TypeError):
        return None


def _med(xs: list[float]) -> str:
    return f"{statistics.median(xs):.2f}" if xs else "–"


def render(game_dirs: list[Path]) -> str:
    lines = [
        "# Performance",
        "",
        "Generated by `python -m replay_worker perf <game_dir>... --write docs/perf.md` from",
        "each game's `_work/worker.jsonl`. Do not edit by hand. A *miss* is real compute; a",
        "*hit* is a restore from the content-hash cache. Wall seconds include lock waits.",
        "`x RT` = video seconds per wall second (higher is faster).",
        "",
        "## Per stage",
        "",
        (
            "| game | stage | resource | misses | hits | fails | median miss s | miss x RT "
            "| median hit s | max GPU-lock wait s |"
        ),
        "|---|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for g in game_dirs:
        dur = _duration(g)
        by_stage: dict[str, list[dict]] = defaultdict(list)
        for r in read_log(g):
            by_stage[r["stage"]].append(r)
        for stage, rs in by_stage.items():
            ok = [r for r in rs if r["status"] == "ok"]
            miss = [r["wall_s"] for r in ok if r.get("cache") in ("miss", "off")]
            hit = [r["wall_s"] for r in ok if r.get("cache") == "hit"]
            fails = len(rs) - len(ok)
            wait = max((r.get("lock_wait_s", 0.0) for r in rs), default=0.0)
            med = statistics.median(miss) if miss else 0.0
            xrt = f"{dur / med:.1f}" if dur and med > 0.05 else "–"
            lines.append(
                f"| {Path(g).name} | {stage} | {rs[-1]['resource']} | {len(miss)} | {len(hit)} "
                f"| {fails} | {_med(miss)} | {xrt} | {_med(hit)} | {wait:.2f} |"
            )
    lines += [
        "",
        "## Per run",
        "",
        "| game | host | run | tasks | misses | hits | wall s | video s | x RT |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for g in game_dirs:
        runs: dict[str, list[dict]] = defaultdict(list)
        for r in read_log(g):
            runs[r["run"]].append(r)
        dur = _duration(g)
        for run_id, rs in runs.items():
            wall = max(r["ended"] for r in rs) - min(r["started"] for r in rs)
            misses = sum(r.get("cache") == "miss" for r in rs)
            hits = sum(r.get("cache") == "hit" for r in rs)
            xrt = f"{dur / wall:.1f}" if dur and wall > 0 else "–"
            lines.append(
                f"| {Path(g).name} | {rs[0].get('host', '?')} | {run_id} | {len(rs)} | {misses} "
                f"| {hits} | {wall:.1f} | {dur if dur is not None else '–'} | {xrt} |"
            )
    return "\n".join(lines) + "\n"
